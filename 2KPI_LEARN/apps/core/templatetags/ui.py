@register.simple_tag
def icon(nom, size=20, stroke=1.75, **attrs):
    """Rend une icône SVG ; aria-hidden car toujours accompagnée d'un libellé."""
    contenu = ICONES.get(nom)
    if contenu is None:
        return ""
    classe = ("icon " + attrs.get("class", "")).strip()
    return format_html(
        '<svg class="{}" width="{}" height="{}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="{}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">{}</svg>',
        classe, size, size, stroke, mark_safe(contenu),
    )


